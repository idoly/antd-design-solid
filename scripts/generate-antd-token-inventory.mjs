import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const version = '6.5.2';
const cli = resolve('node_modules/.bin/antd');
const outputPath = resolve('scripts/antd-token-inventory.json');
const typeOutputPath = resolve('src/config-provider/componentTokens.ts');
const check = process.argv.includes('--check');

function query(...args) {
  const output = execFileSync(cli, ['--format', 'json', '--version', version, ...args], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'inherit'],
  });
  return JSON.parse(output);
}

const components = query('list');
const globalResult = query('token');
const inventory = {
  version,
  globalTokens: (globalResult.tokens ?? []).map(({ name, type, default: defaultValue }) => ({ name, type, default: defaultValue })),
  components: {},
};

for (const { name } of components) {
  const result = query('token', name);
  inventory.components[name] = (result.tokens ?? []).map(({ name: tokenName, type, default: defaultValue }) => ({
    name: tokenName,
    type,
    default: defaultValue,
  }));
}

const serialized = `${JSON.stringify(inventory, null, 2)}\n`;
const tokenMap = Object.entries(inventory.components).map(([component, tokens]) => `  ${JSON.stringify(component)}: ${tokens.length ? tokens.map((token) => JSON.stringify(token.name)).join(' | ') : 'never'};`).join('\n');
const globalTokenNames = inventory.globalTokens.map((token) => JSON.stringify(token.name)).join(' | ');
const typeSource = `// Generated by scripts/generate-antd-token-inventory.mjs from @ant-design/cli@${version}.\nimport type { ThemeToken } from './theme';\n\nexport type ComponentTokenValue = string | number | boolean;\nexport type GlobalTokenName = ${globalTokenNames};\nexport type GlobalThemeTokenOverrides = Partial<Record<GlobalTokenName, ComponentTokenValue>>;\n\nexport interface ComponentTokenNameMap {\n${tokenMap}\n}\n\nexport type ComponentTokenAlgorithm = (token: ThemeToken) => ThemeToken;\nexport type ComponentThemeToken<Name extends keyof ComponentTokenNameMap = keyof ComponentTokenNameMap> =\n  Partial<Record<ComponentTokenNameMap[Name], ComponentTokenValue>> &\n  GlobalThemeTokenOverrides & { algorithm?: boolean | ComponentTokenAlgorithm };\nexport type ConfigComponentThemes = { [Name in keyof ComponentTokenNameMap]?: ComponentThemeToken<Name> };\n`;
if (check) {
  const current = readFileSync(outputPath, 'utf8');
  const currentTypes = readFileSync(typeOutputPath, 'utf8');
  if (current !== serialized || currentTypes !== typeSource) {
    console.error('Ant Design token inventory is stale. Run npm run tokens:update.');
    process.exit(1);
  }
  const tokenCount = Object.values(inventory.components).reduce((sum, tokens) => sum + tokens.length, 0);
  console.log(`Verified ${inventory.globalTokens.length} global and ${tokenCount} component tokens across ${Object.keys(inventory.components).length} Ant Design components.`);
} else {
  writeFileSync(outputPath, serialized);
  writeFileSync(typeOutputPath, typeSource);
  const tokenCount = Object.values(inventory.components).reduce((sum, tokens) => sum + tokens.length, 0);
  console.log(`Wrote ${inventory.globalTokens.length} global and ${tokenCount} component tokens across ${Object.keys(inventory.components).length} components to ${outputPath}.`);
}
